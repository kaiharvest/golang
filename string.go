package main

import "fmt"

func main() {
	fmt.Println("Indra")
	fmt.Println("Dwi")
	fmt.Println("Prabowo")

	fmt.Println(len("Indra"))           // panjnag karakter
	fmt.Println("Indra Dwi Prabowo"[0]) // mengambil karakter array ke 0 dalam bentuk byte nya
	fmt.Println("Indra Dwi"[1])         // mengambil karakter array ke 1 dalam bentuk byte nya
}
